from pathlib import Path

from django.conf import settings
from PIL import Image, ImageStat

from apps.training.models import TrainingRun
from apps.training.services.trainer import _build_model, _image_tensor


def _latest_checkpoint():
    media_root = Path(settings.MEDIA_ROOT).resolve()
    for run in TrainingRun.objects.filter(
        status="completed",
        config__checkpoint__isnull=False,
    ).select_related("dataset").order_by("-created_at"):
        checkpoint_name = run.config.get("checkpoint")
        if not checkpoint_name:
            continue
        checkpoint_path = (media_root / checkpoint_name).resolve()
        if media_root not in checkpoint_path.parents or not checkpoint_path.is_file():
            continue
        return run, checkpoint_path
    return None, None


def _analyze_with_checkpoint(uploaded_file):
    run, checkpoint_path = _latest_checkpoint()
    if not run:
        return None

    try:
        import torch
        from torch import nn
    except ImportError as exc:
        raise RuntimeError("PyTorch is required to use a trained checkpoint.") from exc

    checkpoint = torch.load(checkpoint_path, map_location="cpu")
    classes = checkpoint.get("classes") or []
    image_size = int(checkpoint.get("image_size", 32))
    if not classes or not checkpoint.get("state_dict"):
        raise ValueError("The selected training checkpoint is missing its model metadata.")

    model_version = int(checkpoint.get("model_version", 1))
    model = _build_model(
        torch,
        nn,
        checkpoint["architecture"],
        len(classes),
        model_version=model_version,
    )
    model.load_state_dict(checkpoint["state_dict"])
    model.eval()

    uploaded_file.seek(0)
    with Image.open(uploaded_file) as image:
        tensor = _image_tensor(torch, image, image_size, normalize=model_version >= 3)
    tensor = tensor.unsqueeze(0)

    temperature = max(0.5, min(3.0, float(checkpoint.get("temperature", 1.0))))
    with torch.no_grad():
        # Average the original and horizontally flipped view. Both the RPS
        # gestures and lesion images are orientation-invariant, so this
        # reduces sensitivity to the camera angle without changing the label.
        logits = (model(tensor) + model(torch.flip(tensor, dims=(3,)))) / 2
        probabilities = torch.softmax(logits / temperature, dim=1)[0]
    confidence, predicted_index = torch.max(probabilities, dim=0)
    predicted_index = int(predicted_index.item())
    if predicted_index >= len(classes):
        raise ValueError("The selected training checkpoint returned an unknown class.")

    return {
        "label": classes[predicted_index],
        "confidence": round(float(confidence.item()), 4),
        "review_required": True,
        "mode": "trained_checkpoint",
        "model_run_id": run.pk,
        "model_architecture": run.get_architecture_display(),
        "model_dataset": run.dataset.name if run.dataset else "Unassigned dataset",
        "note": (
            f"Result generated by the completed {run.get_architecture_display()} "
            "checkpoint. Per-image confidence is separate from aggregate test accuracy. "
            "This is not a medical diagnosis; expert review is required."
        ),
        "signals": [
            "Image format validated",
            f"{run.get_architecture_display()} checkpoint applied",
            "Human review recommended",
        ],
    }


def _preview_analysis(uploaded_file):
    """Keep a transparent fallback until a completed checkpoint is available."""
    image = Image.open(uploaded_file).convert("RGB")
    stat = ImageStat.Stat(image)
    brightness = sum(stat.mean) / 3
    red_bias = stat.mean[0] - ((stat.mean[1] + stat.mean[2]) / 2)
    if red_bias > 16 and brightness < 175:
        label, confidence = "Needs expert review", 0.58
    elif brightness > 220:
        label, confidence = "Low-signal image", 0.42
    else:
        label, confidence = "Needs expert review", 0.51
    return {
        "label": label,
        "confidence": confidence,
        "review_required": True,
        "mode": "preview_analysis",
        "note": "No completed trained checkpoint is registered. This preview is not a medical diagnosis.",
        "signals": ["Image format validated", "RGB channels detected", "Human review recommended"],
    }


def analyze_image(uploaded_file):
    """Use the newest completed checkpoint, with an explicit preview fallback."""
    checkpoint_analysis = _analyze_with_checkpoint(uploaded_file)
    if checkpoint_analysis is not None:
        return checkpoint_analysis
    uploaded_file.seek(0)
    return _preview_analysis(uploaded_file)
